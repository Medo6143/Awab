"""Builds src/data/quran/quranUthmani.ts from alquran.cloud's quran-uthmani edition, so the
mushaf works with no network. Usage:
  python tools/quran/build_uthmani.py uthmani.json surahs.json [page1.json page604.json]
The optional page files (/v1/page/N/quran-uthmani) are checked against the result."""
import json, sys

quran = json.load(open(sys.argv[1], encoding='utf-8'))['data']
surahs = json.load(open(sys.argv[2], encoding='utf-8'))['data']

lines = []
n = 0
for s in quran['surahs']:
    for a in s['ayahs']:
        n += 1
        assert a['number'] == n, (a['number'], n)
        text = a['text'].strip()
        assert '|' not in text and '\n' not in text
        lines.append(f"{s['number']}|{a['numberInSurah']}|{a['page']}|{a['juz']}|{a['hizbQuarter']}|{text}")
assert n == 6236, n

meta = [[s['number'], s['name'], s['englishName'], s['numberOfAyahs'], s['revelationType']] for s in surahs]
assert len(meta) == 114

# what the page endpoint returns must match what the bundle gives back
by_num = {i + 1: l.split('|', 5) for i, l in enumerate(lines)}
for path in sys.argv[3:]:
    for a in json.load(open(path, encoding='utf-8'))['data']['ayahs']:
        s, k, p, j, h, t = by_num[a['number']]
        assert (int(s), int(k), int(p), int(j), int(h), t) == (a['surah']['number'], a['numberInSurah'], a['page'], a['juz'], a['hizbQuarter'], a['text'].strip()), a['number']
    print('matches', path)

out = 'src/data/quran/quranUthmani.ts'
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/quran/build_uthmani.py from alquran.cloud quran-uthmani (the text the\n')
    f.write('// mushaf used to fetch page by page). One ayah per line, "surah|ayah|page|juz|hizbQuarter|text",\n')
    f.write('// in mushaf order (line index + 1 = global ayah number). Loaded on first use of the mushaf.\n')
    f.write('export const QURAN_UTHMANI = ' + json.dumps('\n'.join(lines), ensure_ascii=False) + ';\n\n')
    f.write('/** [number, name, englishName, numberOfAyahs, revelationType] for the 114 surahs. */\n')
    f.write('export const SURAH_META: [number, string, string, number, string][] = ' + json.dumps(meta, ensure_ascii=False) + ';\n')
print(out, sum(len(l.encode()) for l in lines) / 1e6, 'MB')
